export function ShogiRules({ style }: { style: PieceStyle }) {
  return (
    <div className="rules">
      <section>
        <h3>Цель игры</h3>
        <p>
          Поставить мат королю соперника (цуми). Играют <b className="cho">сэнтэ</b> — он ходит первым — и{' '}
          <b className="han">готэ</b>. Фигуры у сторон одинакового цвета; чьи они, видно по направлению: острие
          фигуры смотрит на соперника. Если у стороны нет ни одного хода, она проигрывает.
        </p>
      </section>
      <section>
        <h3>Доска</h3>
        <p>
          Фигуры стоят в клетках доски 9×9. Вертикали нумеруются 1–9 справа налево, горизонтали — а–i (一–九) сверху
          вниз, если смотреть со стороны сэнтэ: ход «П 7g–7f» — пешка с поля 7g на 7f. Три дальние от игрока
          горизонтали — его <b>зона превращения</b>.
        </p>
      </section>
      <section>
        <h3>Фигуры</h3>
        <PieceTable rows={SHOGI_RULES} info={SHOGI_PIECES} style={style} game="shogi" />
      </section>
      <section>
        <h3>Превращение</h3>
        <p>
          Если фигура ходит в зону превращения, внутри неё или из неё, её можно перевернуть — превратить (на
          иконке появляется красный «+», иероглиф становится красным). Превращаться не обязательно, но пешка и
          стрелка на последней горизонтали и конь на двух последних превращаются обязательно — иначе им некуда
          ходить. Король и золотой генерал не превращаются. В записи хода «+» — превращение, «=» — отказ от него.
        </p>
      </section>
      <section>
        <h3>Сброс фигур</h3>
        <p>
          Взятая фигура переходит в <b>руку</b> взявшего (превращённая — обратно в обычную) и показывается над или под
          доской. Вместо хода можно поставить фигуру из руки на любое свободное поле — нажмите на неё в руке, затем
          на поле. В записи сброс отмечается звёздочкой: «П*5e». Ограничения: нельзя ставить фигуру туда, откуда у
          неё не будет ходов; нельзя ставить вторую свою непревращённую пешку на ту же вертикаль (нифу); нельзя
          ставить мат сбросом пешки (утифудзумэ) — сделавший это проигрывает. Сброшенная в зону фигура сразу не
          превращается.
        </p>
      </section>
      <section>
        <h3>Повторения</h3>
        <p>
          Если одна и та же позиция (с теми же фигурами в руках и тем же ходом) повторилась четыре раза, это
          сэннититэ — ничья. Но если повторение возникло из-за вечного шаха, проигрывает шахующий.
        </p>
      </section>
    </div>
  );
}

function PieceTable({ rows, info, style, game }: { rows: Row[]; info: Record<string, { ru: string; native: string }>; style: PieceStyle; game: GameId }) {
  return (
    <table className="piece-table">
      <tbody>
        {rows.map(({ t, text, promoted }) => (
          <tr key={t}>
            <td className="piece-cell">
              <PieceIcon piece={t} style={style} size={36} game={game} />
              {game === 'xiangqi' || game === 'manchu' ? (
                <PieceIcon piece={t.toLowerCase()} style={style} size={36} game={game} />
              ) : (
                promoted && <PieceIcon piece={promoted} style={style} size={36} game={game} />
              )}
            </td>
            <td>
              <b>
                {info[t].ru} ({info[t].native})
              </b>
              {promoted && (
                <span className="muted">
                  {' '}
                  → {info[promoted].ru.toLowerCase()} ({info[promoted].native})
                </span>
              )}
              <div>{text}</div>
            </td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

