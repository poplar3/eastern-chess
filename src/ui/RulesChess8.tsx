function PieceTable({ rows, info, style, game }: { rows: Row[]; info: Record<string, PieceInfo>; style: PieceStyle; game: GameId }) {
  return (
    <table className="piece-table">
      <tbody>
        {rows.map(({ t, text }) => (
          <tr key={t}>
            <td className="piece-cell">
              <PieceIcon piece={t} style={style} size={36} game={game} />
              <PieceIcon piece={t.toLowerCase()} style={style} size={36} game={game} />
            </td>
            <td>
              <b>
                {info[t].ru} <span className="muted">({info[t].native})</span>
              </b>
              <div>{text}</div>
            </td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

