const SEEN_KEY = 'janggi.mnemonics.seen.v1';

export function mnemonicsSeen(game: GameId): boolean {
  try {
    const raw = localStorage.getItem(SEEN_KEY);
    return raw ? (JSON.parse(raw) as GameId[]).includes(game) : false;
  } catch {
    return true; // нет хранилища — не надоедаем каждый запуск
  }
}

export function markMnemonicsSeen(game: GameId) {
  try {
    const raw = localStorage.getItem(SEEN_KEY);
    const list = raw ? (JSON.parse(raw) as GameId[]) : [];
    if (!list.includes(game)) localStorage.setItem(SEEN_KEY, JSON.stringify([...list, game]));
  } catch {
    // не критично
  }
}
